const PAST_ENDINGS = ['م', 'ی', '', 'یم', 'ید', 'ند'];
const PRES_ENDINGS = ['م', 'ی', 'د', 'یم', 'ید', 'ند'];

// صرف کامل تمام افعال
for (const v of VERBS) {
  wordSet.add(v.inf);
  wordSet.add(v.past);
  wordSet.add(v.pres);
  wordSet.add(`${v.past}ه`); // صفت مفعولی
  wordSet.add(`${v.past}ن`); // مصدر
  wordSet.add(`${v.pres}نده`); // صفت فاعلی
  wordSet.add(`${v.pres}ش`); // اسم مصدر (گفتش، رفتش، بینش، دانش)
  wordSet.add(`${v.pres}مان`); // گفتمان، ساختمان

  // گذشته ساده و استمراری و منفی
  for (const end of PAST_ENDINGS) {
    const simple = v.past + end;
    wordSet.add(simple);
    wordSet.add(`ن${simple}`);
    wordSet.add(`می${ZWNJ}${simple}`);
    wordSet.add(`نمی${ZWNJ}${simple}`);
  }

  // حال اخباری، التزامی، امری و منفی
  for (const end of PRES_ENDINGS) {
    const simplePres = v.pres + end;
    wordSet.add(`می${ZWNJ}${simplePres}`);
    wordSet.add(`نمی${ZWNJ}${simplePres}`);
    wordSet.add(`ب${simplePres}`);
    wordSet.add(`ن${simplePres}`);
  }

  // نقلی
  for (const end of ['ام', 'ای', 'است', 'ایم', 'اید', 'اند']) {
    wordSet.add(`${v.past}ه‌${end}`);
    wordSet.add(`${v.past}ه ${end}`);
  }
}


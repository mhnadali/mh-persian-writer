// خواندن واژگان پایه موجود
const currentDictPath = path.join(__dirname, '../src/dictionary.ts');
let baseWords = [];
if (fs.existsSync(currentDictPath)) {
  const content = fs.readFileSync(currentDictPath, 'utf8');
  const matches = content.match(/"([^"]+)"/g);
  if (matches) {
    baseWords = matches.map(m => m.replace(/"/g, ''));
  }
}

// ساخت یک فرهنگ واژگان بنیادی و غنی
